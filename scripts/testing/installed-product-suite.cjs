async function (v) {
  const { fs, path, electron, run } = v
  const result = { pass: false, checks: {}, evidence: {} }
  const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
  const check = (condition, label, evidence) => { if (!condition) throw new Error(label + ': ' + JSON.stringify(evidence)); result.checks[label] = true; if (evidence !== undefined) result.evidence[label] = evidence }
  const wait = async (predicate, label) => { const start = Date.now(); while (Date.now() - start < 8000) { if (await predicate()) return; await delay(30) } throw new Error('Timeout: ' + label) }
  const ui = script => v.ui(script)
  const main = script => v.ui(script, 'main')
  const text = () => ui("document.querySelector('.dst-text')?.textContent")
  const history = () => ui('window.api.loadHistory()')
  const sources = () => main("[...document.querySelectorAll('.h-src')].map(el => el.textContent)")
  const trigger = source => { v.window('popup').show(); v.window('popup').webContents.send('translate:trigger', { text: source, ts: Date.now() }) }
  const edit = source => ui(`document.querySelector('.src-text').textContent=${JSON.stringify(source)}; document.querySelector('.src-text').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}))`)
  const chooseMode = async label => {
    await ui("document.querySelector('.es-trigger').click()")
    await wait(() => ui(`[...document.querySelectorAll('.es-item')].some(el=>el.textContent.includes(${JSON.stringify(label)}))`), 'engine menu')
    await ui(`[...document.querySelectorAll('.es-item')].find(el=>el.textContent.includes(${JSON.stringify(label)})).click()`)
  }
  const capture = async name => fs.writeFileSync(path.join(run, name + '.png'), (await v.window('popup').capturePage()).toPNG())
  try {
    const cfg = await main('window.api.loadConfig()')
    check(cfg.target === '中文(简体)' && cfg.closeAction === 'tray' && cfg.customPreserved === 'LEGACY-SYNTHETIC', 'defaults and legacy config', { target: cfg.target, closeAction: cfg.closeAction, customPreserved: cfg.customPreserved })
    const originalHistory = await history()
    check(originalHistory[0].id === 'legacy-id' && originalHistory[0].customPreserved === 'LEGACY', 'legacy history retained')
    await main("window.__historyEvents=[]; window.__configEvents=[]; window.api.onHistoryUpdate(()=>window.api.loadHistory().then(items=>window.__historyEvents.push(items))); window.api.onConfigUpdate(cfg=>window.__configEvents.push(cfg)); true")
    await ui("window.__historyEvents=[]; window.__configEvents=[]; window.api.onHistoryUpdate(()=>window.api.loadHistory().then(items=>window.__historyEvents.push(items))); window.api.onConfigUpdate(cfg=>window.__configEvents.push(cfg)); true")
    await ui('window.api.clearHistory()')
    v.holdHistory = true
    trigger('RACE')
    await wait(async () => await text() === 'RACE fast' && v.writes.length === 1, 'race first result before persistence')
    check(!v.requests.find(r => r.source === 'RACE' && r.engine === 'slow').replied && (await history()).length === 0, 'first success before slow and persistence', { visible: await text(), slowPending: true, historyCount: 0 })
    await ui("document.querySelector('.dst-text').innerText='EDITED FIRST'; document.querySelector('.dst-text').dispatchEvent(new Event('blur'))")
    v.requests.find(r => r.source === 'RACE' && r.engine === 'slow').reply()
    await wait(() => ui("document.querySelector('.race-count')?.textContent==='1/2'"), 'later race comparison')
    check(await text() === 'EDITED FIRST', 'edit survives later result')
    await ui("document.querySelector('.race-cycle').click()")
    await wait(async () => await text() === 'RACE slow', 'comparison switch')
    await ui("document.querySelector('.dst-text').innerText='EDITED SLOW'; document.querySelector('.dst-text').dispatchEvent(new Event('blur'))")
    v.releaseWrites()
    await wait(async () => (await history()).length === 1, 'single race history write')
    check(await text() === 'EDITED SLOW' && (await history())[0].engine === 'DeepSeek', 'one auto history and selected edit survive completion')
    await capture('race-edited-visible')

    await ui('window.api.clearHistory()')
    trigger('OLD_RACE')
    await wait(() => v.requests.filter(r=>r.source === 'OLD_RACE').length === 2, 'old race requests')
    await chooseMode('DeepSeek'); await edit('SINGLE_CURRENT')
    await wait(async () => await text() === 'SINGLE_CURRENT fast', 'new single')
    v.requests.filter(r=>r.source === 'OLD_RACE').forEach((r,i)=>r.reply(i ? 'failure' : 'success'))
    await delay(250)
    check(await text() === 'SINGLE_CURRENT fast' && JSON.stringify((await history()).map(h=>h.src)) === '["SINGLE_CURRENT"]', 'late uncancellable race cannot overwrite single or history')
    trigger('OLD_SINGLE')
    await wait(() => v.requests.some(r=>r.source === 'OLD_SINGLE'), 'old single')
    await chooseMode('Race'); await edit('RACE_CURRENT')
    await wait(() => ui("document.querySelector('.race-count')?.textContent==='1/2'"), 'new race')
    v.requests.filter(r=>r.source === 'OLD_SINGLE').forEach(r=>r.reply())
    await delay(250)
    check(await text() === 'RACE_CURRENT fast' && !(await history()).some(h=>h.src.startsWith('OLD_')) && (await history()).some(h=>h.src === 'SINGLE_CURRENT'), 'late uncancellable single cannot overwrite race and completed history remains')
    check(v.requests.filter(r=>r.source.startsWith('OLD_')).every(r=>r.abortAttempts > 0 && r.replied), 'cancellation attempted while physical responses still arrive', v.requests.filter(r=>r.source.startsWith('OLD_')).map(({source,engine,abortAttempts,replied})=>({source,engine,abortAttempts,replied})))
    trigger('PARTIAL')
    await wait(() => ui("!!document.querySelector('.race-errors')"), 'partial failure')
    check(await text() === 'PARTIAL fast', 'partial failure retains success')
    trigger('ALL_FAIL'); await wait(() => ui("!!document.querySelector('.error-bar')"), 'all fail feedback')
    check(!(await history()).some(h=>h.src === 'ALL_FAIL'), 'all fail has no history')
    trigger('EMPTY'); await wait(() => ui("!!document.querySelector('.error-bar')"), 'empty feedback')
    check(!(await history()).some(h=>h.src === 'EMPTY'), 'empty translation has no history')
    trigger('UI_EDIT'); await wait(async () => await text() === 'UI_EDIT fast', 'editable result')
    await ui("document.querySelector('.dst-text').innerText='EDITED COPY AND SPEECH'; document.querySelector('.dst-text').dispatchEvent(new Event('blur'))")
    await ui("document.querySelector('button[title=\"复制译文\"]').click()")
    await wait(() => electron.clipboard.readText() === 'EDITED COPY AND SPEECH', 'actual clipboard IPC')
    check(true, 'edited translation copies through actual clipboard')
    await ui("window.__speech=[]; window.speechSynthesis.speak = utterance => { window.__speech.push({text:utterance.text,lang:utterance.lang}) }; document.querySelector('button[title=\"朗读译文\"]').click()")
    const speech = await ui('window.__speech')
    check(speech[0]?.text === 'EDITED COPY AND SPEECH', 'speech invoked with edited content', { utterance: speech[0], audibleOutputClaimed: false })
    await ui("document.querySelector('button[title=\"停止朗读\"]').click()")
    const oldTheme = await ui('document.documentElement.dataset.theme')
    await ui("document.querySelector('.theme-btn').click()")
    check(await ui('document.documentElement.dataset.theme') !== oldTheme && ['dark','light'].includes(await ui("localStorage.getItem('translate-app.theme')")), 'theme UI and local storage')
    const oldLang = await ui("document.querySelector('.lang-pair').textContent")
    await ui("document.querySelector('.lang-indicator').click()")
    await wait(async () => await ui("document.querySelector('.lang-pair').textContent") !== oldLang, 'translation direction')
    check(true, 'translation direction toggle')
    await main("window.location.hash='#/settings/general'")
    await wait(() => main("!!document.querySelector('.page-title') && !!document.querySelector('.setting-row')"), 'General settings')
    await main("[...document.querySelectorAll('.setting-row')].find(row=>row.textContent.includes('系统语言')).querySelector('.base-select-trigger, .bs-trigger, button').click()")
    // BaseSelect options use role=option and preserve accessible visible labels.
    const languageControls = await main("[...document.querySelectorAll('[role=option],.base-select-option,.bs-option')].map(el=>({text:el.textContent,cls:el.className}))")
    v.stamp('language-controls', { languageControls })
    const english = await main("(() => {const el=[...document.querySelectorAll('[role=option],.base-select-option,button')].find(el=>el.textContent.trim()==='English'); if(el){el.click();return true} return false})()")
    check(english, 'language option exposed')
    await wait(() => main("document.querySelector('.page-title').textContent==='General'"), 'English settings')
    await wait(async () => (await main('window.api.loadConfig()')).uiLanguage === 'en', 'language setting durable')
    check((await main('window.api.loadConfig()')).uiLanguage === 'en', 'application language through actual settings')

    v.configFailure = true
    await main("(() => {const input=[...document.querySelectorAll('.setting-row')].find(row=>row.textContent.includes('Launch to Tray')).querySelector('input'); input.checked=false; input.dispatchEvent(new Event('change',{bubbles:true}))})()")
    await wait(() => main("!!document.querySelector('.setting-error[role=alert]')"), 'config save error visible')
    check(JSON.parse(fs.readFileSync(path.join(run,'home','.translate-app.config.json'),'utf8')).launchToTray === true, 'failed settings save leaves durable value')
    v.configFailure = false
    await main("(() => {const input=[...document.querySelectorAll('.setting-row')].find(row=>row.textContent.includes('Launch to Tray')).querySelector('input'); input.checked=true; input.dispatchEvent(new Event('change',{bubbles:true}))})()")
    await wait(() => main("!document.querySelector('.setting-error[role=alert]')"), 'config retry clears alert')

    v.historyFailure = true; trigger('HISTORY_FAIL')
    await wait(() => ui("!!document.querySelector('.save-warning')"), 'history save warning')
    check(await text() === 'HISTORY_FAIL fast' && !(await history()).some(h=>h.src === 'HISTORY_FAIL'), 'history failure leaves successful translation and no invented history')
    v.historyFailure = false; trigger('HISTORY_RETRY')
    await wait(async () => (await history()).some(h=>h.src === 'HISTORY_RETRY'), 'history retry')
    const item = (await history()).find(h=>h.src === 'HISTORY_RETRY')
    await main("window.location.hash='#/'")
    await wait(async () => (await sources()).includes('HISTORY_RETRY'), 'Home updates after successful history')
    await main(`[...document.querySelectorAll('.history-item')].find(el=>el.querySelector('.h-src').textContent==='HISTORY_RETRY').querySelector('button[title="收藏"],button[title="Favorite"]').click()`)
    await wait(async () => (await history()).find(h=>h.id === item.id)?.favorite === true, 'favorite update')
    check(await ui('window.__historyEvents.some(items=>items.some(h=>h.id===' + JSON.stringify(item.id) + '&&h.favorite))'), 'favorites broadcast to second subscribed view')
    await ui(`window.api.setFavorite(${JSON.stringify(item.id)},false)`)
    await wait(() => main("![...document.querySelectorAll('.history-item')].find(el=>el.querySelector('.h-src').textContent==='HISTORY_RETRY').querySelector('.favorite')"), 'unfavorite broadcasts')
    await ui(`window.api.deleteHistory(${JSON.stringify(item.id)})`)
    await wait(async () => !(await sources()).includes('HISTORY_RETRY'), 'delete broadcasts')
    await main("document.querySelector('.toolbar .btn-ghost').click()")
    await wait(() => main("!!document.querySelector('.confirm-actions .btn-danger')"), 'clear confirmation')
    await main("document.querySelector('.confirm-actions .btn-danger').click()")
    await wait(async () => !(await history()).length && !(await sources()).length, 'clear broadcasts')
    check(await ui('window.__historyEvents.length') > 4 && await main('window.__historyEvents.length') > 4, 'history favorite unfavorite delete clear notifications')
    // Real successful sessions validate retention through the public IPC/session path.
    await chooseMode('DeepSeek')
    for (let i=0; i<22; i++) {
      trigger('RETAIN_' + i)
      await wait(async () => (await history()).some(h=>h.src === 'RETAIN_' + i), 'retention session ' + i)
      if (i === 0) await ui(`window.api.setFavorite(${JSON.stringify((await history())[0].id)},true)`)
    }
    const retained = await history()
    check(retained.length === 21 && retained.filter(h=>!h.favorite).length === 20 && retained.some(h=>h.favorite && h.src === 'RETAIN_0'), 'favorites plus twenty recent retained', { count: retained.length, recent: retained.filter(h=>!h.favorite).length })
    check((await main('window.api.loadConfig()')).providers.openai.apiKey === 'SYNTHETIC-ONLY', 'partial saves preserve synthetic provider config')
    await ui("document.querySelector('button[title=\"固定窗口\"]').click()")
    await wait(() => v.window('popup').isAlwaysOnTop(), 'native pin')
    v.window('main').show(); v.window('main').focus(); await delay(250)
    check(v.window('popup').isVisible() && v.window('popup').isAlwaysOnTop(), 'pinned popup survives native blur')
    await ui("document.querySelector('button[title=\"固定窗口\"]').click()")
    await wait(() => ui('window.api.popupReady().then(state=>!state.pinned)'), 'unpin')
    v.window('popup').focus(); await delay(100); v.window('main').focus(); await delay(500)
    await wait(() => !v.window('popup').isVisible(), 'unpin native blur hides')
    check(true, 'unpin and native blur hide', { alwaysOnTopAfterUnpin: v.window('popup').isAlwaysOnTop() })
    v.window('popup').show(); await delay(100)
    v.window('popup').setSize(460,540)
    check(JSON.stringify(v.window('popup').getSize()) === '[460,540]', 'native resize strategy')
    await main('window.api.resetPopupBounds()')
    await wait(() => JSON.stringify(v.window('popup').getSize()) === '[380,500]', 'bounds reset')
    await ui("document.querySelector('.popup-actions button[title=\"关闭\"]').click()")
    await wait(() => !v.window('popup').isVisible(), 'close hides')
    const popupId = v.window('popup').id
    trigger('FINAL_VISIBLE'); await wait(async () => await text() === 'FINAL_VISIBLE fast', 'same popup reused')
    check(v.window('popup').id === popupId && electron.BrowserWindow.getAllWindows().length === 2, 'close and hide reuse one popup')
    await capture('final-visible')
    v.window('main').close(); await delay(150)
    check(!v.window('main').isVisible(), 'main close to tray')
    v.menus[0].template.find(item=>item.label==='打开设置').click()
    await wait(() => v.window('main').isVisible(), 'actual tray menu callback')
    check(true, 'tray menu open callback', { physicalTrayClick: false })
    await main("window.location.hash='#/settings/general'")
    await wait(() => main("document.querySelector('.page-title')?.textContent==='General'"), 'quit pending settings')
    // Quit is scheduled immediately after this mutation by the outer controller.
    await main("(() => {const input=[...document.querySelectorAll('.setting-row')].find(row=>row.textContent.includes('Launch to Tray')).querySelector('input'); input.checked=false; input.dispatchEvent(new Event('change',{bubbles:true}))})()")
    check(true, 'immediate quit draft prepared')
    result.pass = true
    return result
  } finally { fs.writeFileSync(path.join(run, 'functional-result.json'), JSON.stringify(result, null, 2)) }
}
